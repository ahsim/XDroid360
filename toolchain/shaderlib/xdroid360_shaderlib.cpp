// Okumura's LZSS as CryEngine's resource files use it: 4096-byte ring of spaces, 18-byte
// matches, threshold 2.
std::vector<uint8_t> CryLzss(const uint8_t* src, size_t n) {
  constexpr size_t N = 4096, F = 18, kThreshold = 2;
  uint8_t ring[N];
  std::memset(ring, ' ', N);
  size_t r = N - F, i = 0;
  unsigned flags = 0;
  std::vector<uint8_t> out;
  while (i < n) {
    flags >>= 1;
    if (!(flags & 0x100)) {
      flags = src[i++] | 0xFF00u;
      if (i >= n) break;
    }
    if (flags & 1) {
      const uint8_t c = src[i++];
      out.push_back(c);
      ring[r] = c;
      r = (r + 1) & (N - 1);
    } else {
      if (i + 1 >= n) break;
      const uint8_t lo = src[i], hi = src[i + 1];
      i += 2;
      const size_t at = lo | size_t(hi & 0xF0) << 4;
      const size_t len = (hi & 0x0F) + kThreshold + 1;
      for (size_t k = 0; k < len; ++k) {
        const uint8_t c = ring[(at + k) & (N - 1)];
        out.push_back(c);
        ring[r] = c;
        r = (r + 1) & (N - 1);
      }
    }
  }
  return out;
}

