struct Container {
  std::string name;  // <erf entry>_<offset in hex>.<vs|ps>, as the PC pipeline named its files
  std::vector<uint8_t> data;
  bool vertex = false;
};

uint32_t Le32(const std::vector<uint8_t>& d, size_t o) {
  return uint32_t(d[o]) | uint32_t(d[o + 1]) << 8 | uint32_t(d[o + 2]) << 16 | uint32_t(d[o + 3]) << 24;
}
uint32_t Be32(const std::vector<uint8_t>& d, size_t o) {
  return uint32_t(d[o]) << 24 | uint32_t(d[o + 1]) << 16 | uint32_t(d[o + 2]) << 8 | uint32_t(d[o + 3]);
}

std::vector<uint8_t> ReadFile(const std::string& path) {
  std::ifstream f(path, std::ios::binary | std::ios::ate);
  if (!f) throw std::runtime_error("can't open " + path);
  const std::streamoff n = f.tellg();
  if (n < 0) throw std::runtime_error("can't read " + path);
  std::vector<uint8_t> d(static_cast<size_t>(n));
  f.seekg(0);
  if (!f.read(reinterpret_cast<char*>(d.data()), d.size())) throw std::runtime_error("short read of " + path);
  return d;
}

