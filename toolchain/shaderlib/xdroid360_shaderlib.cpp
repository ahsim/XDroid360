uint16_t Le16(const std::vector<uint8_t>& d, size_t o) { return uint16_t(d[o] | d[o + 1] << 8); }

std::vector<Container> ExtractFromPak(const std::vector<uint8_t>& pak) {
  // The end of central directory record, at most 64 KB of comment from the end.
  size_t eocd = std::string::npos;
  for (size_t p = pak.size() >= 22 ? pak.size() - 22 : 0; p + 22 <= pak.size(); --p) {
    if (Le32(pak, p) == 0x06054B50) {
      eocd = p;
      break;
    }
    if (p == 0 || pak.size() - p > 22 + 65535) break;
  }
  if (eocd == std::string::npos) throw std::invalid_argument("not a zip (no end of central directory)");
  const uint32_t entries = Le16(pak, eocd + 10), cd = Le32(pak, eocd + 16);
  std::vector<Container> out;
  std::set<std::vector<uint8_t>> seen;
  size_t p = cd;
  for (uint32_t k = 0; k < entries; ++k) {
    if (p + 46 > pak.size() || Le32(pak, p) != 0x02014B50) throw std::invalid_argument("zip central directory damaged");
    const uint16_t method = Le16(pak, p + 10);
    const uint32_t csize = Le32(pak, p + 20), usize = Le32(pak, p + 24);
    const uint16_t nlen = Le16(pak, p + 28), elen = Le16(pak, p + 30), clen = Le16(pak, p + 32);
    const uint32_t local = Le32(pak, p + 42);
    std::string name(reinterpret_cast<const char*>(pak.data() + p + 46), nlen);
    p += 46 + size_t(nlen) + elen + clen;
    for (char& c : name) c = c == '\\' ? '/' : char(std::tolower(static_cast<unsigned char>(c)));
    if (name.rfind("shaders/cache/x360/", 0) != 0) continue;
    if (size_t(local) + 30 > pak.size()) continue;
    const size_t data = size_t(local) + 30 + Le16(pak, local + 26) + Le16(pak, local + 28);
    if (data > pak.size() || csize > pak.size() - data) continue;
    std::vector<uint8_t> blob;
    if (method == 0) blob.assign(pak.begin() + data, pak.begin() + data + csize);
    else if (method == 8) blob = Inflate(pak.data() + data, csize, usize, -15);
    else if (method == 13) blob = XMemDecompress(pak.data() + data, csize, usize);
    if (blob.empty()) continue;
    const std::string base = name.substr(name.find_last_of('/') + 1);
    ScanContainers(base, blob, seen, out);
    if (blob.size() < 16 || std::memcmp(blob.data(), "KCPC", 4) != 0) continue;
    // CResFile: [KCPC][version][entry count][directory offset], the directory at the end:
    // {name CRC, size << 8 | flags, offset} per entry; an entry is a BE size and LZSS data.
    const uint32_t count = Be32(blob, 8), dir = Be32(blob, 12);
    if (dir > blob.size() || uint64_t(count) * 12 > blob.size() - dir) continue;
    for (uint32_t i = 0; i < count; ++i) {
      const uint32_t size = Be32(blob, dir + i * 12 + 4) >> 8, off = Be32(blob, dir + i * 12 + 8);
      if (off > blob.size() || size > blob.size() - off || size <= 4) continue;
      ScanContainers(base + "_" + std::to_string(i), CryLzss(blob.data() + off + 4, size - 4), seen, out);
    }
  }
  return out;
}

// Which game's shaders the file holds: Dragon Age's shaders.erf or State of Decay's shaders.pak.
std::vector<Container> ExtractContainers(const std::vector<uint8_t>& file) {
  if (file.size() >= 0x20 && std::memcmp(file.data(), "ERF V2.1", 8) == 0) return ExtractFromErf(file);
  if (file.size() >= 4 && std::memcmp(file.data(), "PK\x03\x04", 4) == 0) return ExtractFromPak(file);
  throw std::invalid_argument("neither an ERF V2.1 (shaders.erf) nor a zip (shaders.pak)");
}

struct Result {
  std::vector<uint32_t> spirv;
  std::string hlsl;
  std::string error;  // empty when it compiled
};

std::string FirstErrorLine(const std::string& log) {
  size_t start = 0;
  while (start < log.size()) {
    size_t end = log.find('\n', start);
    if (end == std::string::npos) end = log.size();
    const std::string line = log.substr(start, end - start);
    const size_t at = line.find("error: ");
    if (at != std::string::npos) return line.substr(at + 7, 160);
    start = end + 1;
  }
  return log.substr(0, 160);
}

// The PC pipeline's dxc.exe command line, in-process:
//   -spirv -T <vs|ps>_6_6 -E main -HV 2021 -fspv-target-env=vulkan1.2 -fvk-use-dx-layout
//   -Werror=parameter-usage [-fvk-invert-y for vertex shaders]
// (Its -I only named shader_common.h's folder; XenosRecomp pastes that header into the HLSL.)
void Compile(IDxcCompiler3* dxc, const Container& c, const std::string& hlsl, Result& r) {
  std::vector<std::wstring> a = {L"-spirv", L"-T", c.vertex ? L"vs_6_6" : L"ps_6_6", L"-E", L"main",
                                 L"-HV", L"2021", L"-fspv-target-env=vulkan1.2", L"-fvk-use-dx-layout",
                                 L"-Werror=parameter-usage"};
  if (c.vertex) a.push_back(L"-fvk-invert-y");
  std::vector<LPCWSTR> args;
  for (auto& s : a) args.push_back(s.c_str());
  DxcBuffer src{hlsl.data(), hlsl.size(), DXC_CP_UTF8};
  IDxcResult* result = nullptr;
  if (FAILED(dxc->Compile(&src, args.data(), static_cast<UINT32>(args.size()), nullptr,
                          IID_PPV_ARGS(&result))) || !result) {
    r.error = "dxc: Compile failed";
    return;
  }
  HRESULT status = E_FAIL;
  result->GetStatus(&status);
  if (FAILED(status)) {
    IDxcBlobUtf8* errors = nullptr;
    std::string log;
    if (SUCCEEDED(result->GetOutput(DXC_OUT_ERRORS, IID_PPV_ARGS(&errors), nullptr)) && errors) {
      log.assign(errors->GetStringPointer(), errors->GetStringLength());
      errors->Release();
    }
    r.error = "dxc: " + FirstErrorLine(log);
  } else {
    IDxcBlob* object = nullptr;
    if (SUCCEEDED(result->GetOutput(DXC_OUT_OBJECT, IID_PPV_ARGS(&object), nullptr)) && object) {
      const size_t n = object->GetBufferSize();
      if (n % 4) {
        r.error = "dxc: SPIR-V size not a multiple of 4";
      } else {
        r.spirv.resize(n / 4);
        std::memcpy(r.spirv.data(), object->GetBufferPointer(), n);
      }
      object->Release();
    } else {
      r.error = "dxc: no output";
    }
  }
  result->Release();
}

long PeakMemoryKb() {
#ifdef _WIN32
  PROCESS_MEMORY_COUNTERS pmc{};
  GetProcessMemoryInfo(GetCurrentProcess(), &pmc, sizeof(pmc));
  return long(pmc.PeakWorkingSetSize / 1024);
#else
  rusage ru{};
  getrusage(RUSAGE_SELF, &ru);
  return ru.ru_maxrss;  // KB on Linux
#endif
}

