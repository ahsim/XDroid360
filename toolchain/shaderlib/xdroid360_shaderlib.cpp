// XDroid360: the native renderer's shader library (nfsmw_shaders.nfsp), built on the phone from
// the player's own game. One process does what the PC pipeline did with four tools:
//   1. read Dragon Age: Origins' shaders.erf (ERF V2.1, zlib entries) and find the Xbox 360
//      shader containers in it (magic 0x102A110x, as XenosRecomp reads them);
//   2. translate each container to HLSL with XenosRecomp (the nfsmw fork, NFSMW_RECOMP);
//   3. compile the HLSL to SPIR-V with DXC, in-process, with the PC pipeline's exact arguments;
//   4. pack the containers and their SPIR-V with the renderer's own EmpaquetarShaders, load the
//      result back and look every container up in it.
// Containers XenosRecomp or DXC rejects are left out and listed: the renderer skips draws it has
// no shader for.
//
// Usage: libshaderlib.so <shaders.erf> <out.nfsp> [-j N] [--hlsl <dir>]
// stdout, one line each:
//   containers <n>
//   progress <done>/<total>              (every 10 shaders, and at the end)
//   left out <name>: <reason>
//   shaders: <n> of <m> translated, <k> left out
//   library <bytes> bytes, <ms> ms, peak memory <KB> KB
// Exit: 0 library written (even with some left out); 1 failed (message on stderr); 2 the input
// is not a shaders.erf.
// The output is written to <out.nfsp>.tmp and renamed, so a failed run leaves no partial file.
// No other scratch files: everything else stays in memory.
//
// The library is game data: it stays on the player's phone and is never distributed.
//
// Licence: this file is MIT like the rest of XDroid360's own code, but the binary links the
// native renderer's nfsmw_shader_library.cpp (GPL-3.0, from nfsmw-android), so libshaderlib.so
// as a whole is GPL-3.0. Built by toolchain/build_tools.sh shaderlib.

