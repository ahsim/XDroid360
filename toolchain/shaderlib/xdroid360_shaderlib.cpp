namespace {

struct Container {
  std::string name;  // <erf entry>_<offset in hex>.<vs|ps>, as the PC pipeline named its files
  std::vector<uint8_t> data;
  bool vertex = false;
};

uint32_t Le32(const std::vector<uint8_t>& d, size_t o) {
  return uint32_t(d[o]) | uint32_t(d[o + 1]) << 8 | uint32_t(d[o + 2]) << 16 | uint32_t(d[o + 3]) << 24;
}
uint32_t Be32(const std::vector<uint8_t>& d, size_t o) {
  return uint32_t(d[o]) << 24 | uint32_t(d[o + 1]) << 16 | uint32_t(d[o + 2]) << 8 | uint32_t(d[o + 3]);
}

std::vector<uint8_t> ReadFile(const std::string& path) {
  std::ifstream f(path, std::ios::binary | std::ios::ate);
  if (!f) throw std::runtime_error("can't open " + path);
  const std::streamoff n = f.tellg();
  if (n < 0) throw std::runtime_error("can't read " + path);
  std::vector<uint8_t> d(static_cast<size_t>(n));
  f.seekg(0);
  if (!f.read(reinterpret_cast<char*>(d.data()), d.size())) throw std::runtime_error("short read of " + path);
  return d;
}

// zlib stream first, raw deflate if that fails (as dao_shaders_extract.py). Empty on failure.
std::vector<uint8_t> Inflate(const uint8_t* src, size_t n, size_t expected, int window_bits) {
  std::vector<uint8_t> out(expected ? expected : n * 4);
  z_stream z{};
  if (inflateInit2(&z, window_bits) != Z_OK) return {};
  z.next_in = const_cast<Bytef*>(src);
  z.avail_in = static_cast<uInt>(n);
  int r = Z_OK;
  size_t have = 0;
  while (r == Z_OK) {
    if (have == out.size()) out.resize(out.size() * 2);
    z.next_out = out.data() + have;
    z.avail_out = static_cast<uInt>(out.size() - have);
    r = inflate(&z, Z_NO_FLUSH);
    have = out.size() - z.avail_out;
  }
  inflateEnd(&z);
  if (r != Z_STREAM_END) return {};
  out.resize(have);
  return out;
}

// dao_shaders_extract.py, step for step: every ERF entry, decompressed, scanned for containers;
// each distinct container once, the first time it is seen.
std::vector<Container> ExtractContainers(const std::vector<uint8_t>& erf) {
  if (erf.size() < 0x20 || std::memcmp(erf.data(), "ERF V2.1", 8) != 0)
    throw std::invalid_argument("not an ERF V2.1 file");
  const uint32_t count = Le32(erf, 0x10);
  if (0x20 + uint64_t(count) * 44 > erf.size()) throw std::invalid_argument("ERF entry table truncated");
  std::vector<Container> out;
  std::set<std::vector<uint8_t>> seen;
  for (uint32_t i = 0; i < count; ++i) {
    const size_t e = 0x20 + size_t(i) * 44;
    std::string name(reinterpret_cast<const char*>(erf.data() + e), 32);
    name = name.substr(0, name.find('\0'));
    const uint32_t off = Le32(erf, e + 32), packed = Le32(erf, e + 36), size = Le32(erf, e + 40);
    if (off > erf.size() || packed > erf.size() - off) continue;
    std::vector<uint8_t> blob;
    if (packed == size) {
      blob.assign(erf.begin() + off, erf.begin() + off + packed);
    } else {
      blob = Inflate(erf.data() + off, packed, size, 15);
      if (blob.empty()) blob = Inflate(erf.data() + off, packed, size, -15);
      if (blob.empty()) continue;
    }
    size_t pos = 0;
    while (pos + 3 <= blob.size()) {
      const uint8_t* hit = static_cast<const uint8_t*>(
          std::memchr(blob.data() + pos, 0x10, blob.size() - pos));
      if (!hit) break;
      pos = hit - blob.data();
      if (pos + 3 > blob.size()) break;
      if (blob[pos + 1] == 0x2A && blob[pos + 2] == 0x11 && pos + 36 <= blob.size() &&
          (blob[pos + 3] == 0 || blob[pos + 3] == 1)) {
        const uint32_t flags = Be32(blob, pos), vsize = Be32(blob, pos + 4), psize = Be32(blob, pos + 8);
        if (vsize >= 24 && uint64_t(vsize) + psize <= blob.size() - pos && psize < (1u << 20)) {
          std::vector<uint8_t> c(blob.begin() + pos, blob.begin() + pos + vsize + psize);
          const bool vertex = flags & 1;
          if (seen.insert(c).second) {
            char suffix[32];
            std::snprintf(suffix, sizeof(suffix), "_%zx.%s", pos, vertex ? "vs" : "ps");
            out.push_back({name + suffix, std::move(c), vertex});
          }
          pos += vsize + psize;
          continue;
        }
      }
      ++pos;
    }
  }
  return out;
}

struct Result {
  std::vector<uint32_t> spirv;
  std::string hlsl;
  std::string error;  // empty when it compiled
};

std::string FirstErrorLine(const std::string& log) {
  size_t start = 0;
  while (start < log.size()) {
    size_t end = log.find('\n', start);
    if (end == std::string::npos) end = log.size();
    const std::string line = log.substr(start, end - start);
    const size_t at = line.find("error: ");
    if (at != std::string::npos) return line.substr(at + 7, 160);
    start = end + 1;
  }
  return log.substr(0, 160);
}

// The PC pipeline's dxc.exe command line, in-process:
//   -spirv -T <vs|ps>_6_6 -E main -HV 2021 -fspv-target-env=vulkan1.2 -fvk-use-dx-layout
//   -Werror=parameter-usage [-fvk-invert-y for vertex shaders]
// (Its -I only named shader_common.h's folder; XenosRecomp pastes that header into the HLSL.)
void Compile(IDxcCompiler3* dxc, const Container& c, const std::string& hlsl, Result& r) {
  std::vector<std::wstring> a = {L"-spirv", L"-T", c.vertex ? L"vs_6_6" : L"ps_6_6", L"-E", L"main",
                                 L"-HV", L"2021", L"-fspv-target-env=vulkan1.2", L"-fvk-use-dx-layout",
                                 L"-Werror=parameter-usage"};
  if (c.vertex) a.push_back(L"-fvk-invert-y");
  std::vector<LPCWSTR> args;
  for (auto& s : a) args.push_back(s.c_str());
  DxcBuffer src{hlsl.data(), hlsl.size(), DXC_CP_UTF8};
  IDxcResult* result = nullptr;
  if (FAILED(dxc->Compile(&src, args.data(), static_cast<UINT32>(args.size()), nullptr,
                          IID_PPV_ARGS(&result))) || !result) {
    r.error = "dxc: Compile failed";
    return;
  }
  HRESULT status = E_FAIL;
  result->GetStatus(&status);
  if (FAILED(status)) {
    IDxcBlobUtf8* errors = nullptr;
    std::string log;
    if (SUCCEEDED(result->GetOutput(DXC_OUT_ERRORS, IID_PPV_ARGS(&errors), nullptr)) && errors) {
      log.assign(errors->GetStringPointer(), errors->GetStringLength());
      errors->Release();
    }
    r.error = "dxc: " + FirstErrorLine(log);
  } else {
    IDxcBlob* object = nullptr;
    if (SUCCEEDED(result->GetOutput(DXC_OUT_OBJECT, IID_PPV_ARGS(&object), nullptr)) && object) {
      const size_t n = object->GetBufferSize();
      if (n % 4) {
        r.error = "dxc: SPIR-V size not a multiple of 4";
      } else {
        r.spirv.resize(n / 4);
        std::memcpy(r.spirv.data(), object->GetBufferPointer(), n);
      }
      object->Release();
    } else {
      r.error = "dxc: no output";
    }
  }
  result->Release();
}

long PeakMemoryKb() {
#ifdef _WIN32
  PROCESS_MEMORY_COUNTERS pmc{};
  GetProcessMemoryInfo(GetCurrentProcess(), &pmc, sizeof(pmc));
  return long(pmc.PeakWorkingSetSize / 1024);
#else
  rusage ru{};
  getrusage(RUSAGE_SELF, &ru);
  return ru.ru_maxrss;  // KB on Linux
#endif
}

void WriteFile(const std::string& path, const void* data, size_t n) {
  std::ofstream f(path, std::ios::binary | std::ios::trunc);
  if (!f.write(static_cast<const char*>(data), n) || !f.flush()) throw std::runtime_error("can't write " + path);
}

}  // namespace

int main(int argc, char** argv) {
  const auto start = std::chrono::steady_clock::now();
  try {
    std::string erf_path, out_path, hlsl_dir;
    unsigned jobs = std::thread::hardware_concurrency();
    for (int i = 1; i < argc; ++i) {
      const std::string a = argv[i];
      if ((a == "-j" || a == "--jobs") && i + 1 < argc) jobs = static_cast<unsigned>(std::stoul(argv[++i]));
      else if (a == "--hlsl" && i + 1 < argc) hlsl_dir = argv[++i];
      else if (erf_path.empty()) erf_path = a;
      else if (out_path.empty()) out_path = a;
      else throw std::runtime_error("unexpected argument " + a);
    }
    if (erf_path.empty() || out_path.empty()) {
      std::fprintf(stderr, "usage: %s <shaders.erf> <out.nfsp> [-j N] [--hlsl <dir>]\n", argv[0]);
      return 1;
    }
    if (jobs == 0) jobs = 1;

    std::vector<Container> containers;
    try {
      containers = ExtractContainers(ReadFile(erf_path));
    } catch (const std::invalid_argument& e) {
      std::fprintf(stderr, "%s: %s\n", erf_path.c_str(), e.what());
      return 2;
    }
    if (containers.empty()) {
      std::fprintf(stderr, "%s: no shader containers\n", erf_path.c_str());
      return 2;
    }
    std::printf("containers %zu\n", containers.size());
    std::fflush(stdout);

    const std::string_view include(reinterpret_cast<const char*>(kShaderCommon), sizeof(kShaderCommon));
    std::vector<Result> results(containers.size());
    std::atomic<size_t> next{0}, done{0};
    std::mutex print;
    std::atomic<bool> dxc_missing{false};
    auto work = [&] {
      IDxcCompiler3* dxc = nullptr;
      if (FAILED(DxcCreateInstance(CLSID_DxcCompiler, IID_PPV_ARGS(&dxc))) || !dxc) {
        dxc_missing = true;
        return;
      }
      for (size_t i; (i = next++) < containers.size();) {
        Result& r = results[i];
        ShaderRecompiler recompiler;
        try {
          recompiler.recompile(containers[i].data.data(), include);
        } catch (const std::exception& e) {
          r.error = std::string("xenosrecomp: ") + e.what();
        }
        if (r.error.empty() && recompiler.out.empty()) r.error = "xenosrecomp: no output";
        if (r.error.empty()) {
          Compile(dxc, containers[i], recompiler.out, r);
          if (!hlsl_dir.empty()) r.hlsl = std::move(recompiler.out);
        }
        const size_t d = ++done;
        if (d % 10 == 0 || d == containers.size()) {
          std::lock_guard<std::mutex> lock(print);
          std::printf("progress %zu/%zu\n", d, containers.size());
          std::fflush(stdout);
        }
      }
      dxc->Release();
    };
    std::vector<std::thread> threads;
    for (unsigned t = 0; t < jobs; ++t) threads.emplace_back(work);
    for (auto& t : threads) t.join();
    if (dxc_missing) throw std::runtime_error("DXC could not be created (libdxcompiler.so missing?)");

    std::vector<nfsmw::native::Shader> shaders;
    for (size_t i = 0; i < containers.size(); ++i) {
      const Result& r = results[i];
      if (!hlsl_dir.empty() && !r.hlsl.empty())
        WriteFile(hlsl_dir + "/" + containers[i].name + ".hlsl", r.hlsl.data(), r.hlsl.size());
      if (!r.error.empty()) {
        std::printf("left out %s: %s\n", containers[i].name.c_str(), r.error.c_str());
        continue;
      }
      nfsmw::native::Shader s;
      s.original = containers[i].data;
      s.spirv = r.spirv;
      shaders.push_back(std::move(s));
    }
    if (shaders.empty()) throw std::runtime_error("no shader compiled");
    std::vector<std::vector<uint8_t>> originals;
    for (const auto& s : shaders) originals.push_back(s.original);
    const size_t count = shaders.size();

    std::vector<uint8_t> package = nfsmw::native::EmpaquetarShaders(std::move(shaders));
    nfsmw::native::BibliotecaShaders library;
    library.Cargar(package);
    for (const auto& o : originals)
      if (!library.Buscar(o)) throw std::runtime_error("a shader can't be found after packing");

    const std::string tmp = out_path + ".tmp";
    WriteFile(tmp, package.data(), package.size());
    std::remove(out_path.c_str());
    if (std::rename(tmp.c_str(), out_path.c_str()) != 0) throw std::runtime_error("can't rename " + tmp);

    const auto ms = std::chrono::duration_cast<std::chrono::milliseconds>(
                        std::chrono::steady_clock::now() - start).count();
    std::printf("shaders: %zu of %zu translated, %zu left out\n", count, containers.size(),
                containers.size() - count);
    std::printf("library %zu bytes, %lld ms, peak memory %ld KB\n", package.size(),
                static_cast<long long>(ms), PeakMemoryKb());
    return 0;
  } catch (const std::exception& e) {
    std::fprintf(stderr, "error: %s\n", e.what());
    return 1;
  }
}
