int main(int argc, char** argv) {
  const auto start = std::chrono::steady_clock::now();
  try {
    std::string erf_path, out_path, hlsl_dir;
    unsigned jobs = std::thread::hardware_concurrency();
    for (int i = 1; i < argc; ++i) {
      const std::string a = argv[i];
      if ((a == "-j" || a == "--jobs") && i + 1 < argc) jobs = static_cast<unsigned>(std::stoul(argv[++i]));
      else if (a == "--hlsl" && i + 1 < argc) hlsl_dir = argv[++i];
      else if (erf_path.empty()) erf_path = a;
      else if (out_path.empty()) out_path = a;
      else throw std::runtime_error("unexpected argument " + a);
    }
    if (erf_path.empty() || out_path.empty()) {
      std::fprintf(stderr, "usage: %s <shaders.erf> <out.nfsp> [-j N] [--hlsl <dir>]\n", argv[0]);
      return 1;
    }
    if (jobs == 0) jobs = 1;

    std::vector<Container> containers;
    try {
      containers = ExtractContainers(ReadFile(erf_path));
    } catch (const std::invalid_argument& e) {
      std::fprintf(stderr, "%s: %s\n", erf_path.c_str(), e.what());
      return 2;
    }
    if (containers.empty()) {
      std::fprintf(stderr, "%s: no shader containers\n", erf_path.c_str());
      return 2;
    }
    std::printf("containers %zu\n", containers.size());
    std::fflush(stdout);

    const std::string_view include(reinterpret_cast<const char*>(kShaderCommon), sizeof(kShaderCommon));
    std::vector<Result> results(containers.size());
    std::atomic<size_t> next{0}, done{0};
    std::mutex print;
    std::atomic<bool> dxc_missing{false};
    auto work = [&] {
      IDxcCompiler3* dxc = nullptr;
      if (FAILED(DxcCreateInstance(CLSID_DxcCompiler, IID_PPV_ARGS(&dxc))) || !dxc) {
        dxc_missing = true;
        return;
      }
      for (size_t i; (i = next++) < containers.size();) {
        Result& r = results[i];
        ShaderRecompiler recompiler;
        try {
          recompiler.recompile(containers[i].data.data(), include);
        } catch (const std::exception& e) {
          r.error = std::string("xenosrecomp: ") + e.what();
        }
        if (r.error.empty() && recompiler.out.empty()) r.error = "xenosrecomp: no output";
        if (r.error.empty()) {
          Compile(dxc, containers[i], recompiler.out, r);
          if (!hlsl_dir.empty()) r.hlsl = std::move(recompiler.out);
        }
        const size_t d = ++done;
        if (d % 10 == 0 || d == containers.size()) {
          std::lock_guard<std::mutex> lock(print);
          std::printf("progress %zu/%zu\n", d, containers.size());
          std::fflush(stdout);
        }
      }
      dxc->Release();
    };
    std::vector<std::thread> threads;
    for (unsigned t = 0; t < jobs; ++t) threads.emplace_back(work);
    for (auto& t : threads) t.join();
    if (dxc_missing) throw std::runtime_error("DXC could not be created (libdxcompiler.so missing?)");

    std::vector<nfsmw::native::Shader> shaders;
    for (size_t i = 0; i < containers.size(); ++i) {
      const Result& r = results[i];
      if (!hlsl_dir.empty() && !r.hlsl.empty())
        WriteFile(hlsl_dir + "/" + containers[i].name + ".hlsl", r.hlsl.data(), r.hlsl.size());
      if (!r.error.empty()) {
        std::printf("left out %s: %s\n", containers[i].name.c_str(), r.error.c_str());
        continue;
      }
      nfsmw::native::Shader s;
      s.original = containers[i].data;
      s.spirv = r.spirv;
      shaders.push_back(std::move(s));
    }
    if (shaders.empty()) throw std::runtime_error("no shader compiled");
    std::vector<std::vector<uint8_t>> originals;
    for (const auto& s : shaders) originals.push_back(s.original);
    const size_t count = shaders.size();

    std::vector<uint8_t> package = nfsmw::native::EmpaquetarShaders(std::move(shaders));
    nfsmw::native::BibliotecaShaders library;
    library.Cargar(package);
    for (const auto& o : originals)
      if (!library.Buscar(o)) throw std::runtime_error("a shader can't be found after packing");

    const std::string tmp = out_path + ".tmp";
    WriteFile(tmp, package.data(), package.size());
    std::remove(out_path.c_str());
    if (std::rename(tmp.c_str(), out_path.c_str()) != 0) throw std::runtime_error("can't rename " + tmp);

    const auto ms = std::chrono::duration_cast<std::chrono::milliseconds>(
                        std::chrono::steady_clock::now() - start).count();
    std::printf("shaders: %zu of %zu translated, %zu left out\n", count, containers.size(),
                containers.size() - count);
    std::printf("library %zu bytes, %lld ms, peak memory %ld KB\n", package.size(),
                static_cast<long long>(ms), PeakMemoryKb());
    return 0;
  } catch (const std::exception& e) {
    std::fprintf(stderr, "error: %s\n", e.what());
    return 1;
  }
}
