// zlib stream first, raw deflate if that fails (as dao_shaders_extract.py). Empty on failure.
std::vector<uint8_t> Inflate(const uint8_t* src, size_t n, size_t expected, int window_bits) {
  std::vector<uint8_t> out(expected ? expected : n * 4);
  z_stream z{};
  if (inflateInit2(&z, window_bits) != Z_OK) return {};
  z.next_in = const_cast<Bytef*>(src);
  z.avail_in = static_cast<uInt>(n);
  int r = Z_OK;
  size_t have = 0;
  while (r == Z_OK) {
    if (have == out.size()) out.resize(out.size() * 2);
    z.next_out = out.data() + have;
    z.avail_out = static_cast<uInt>(out.size() - have);
    r = inflate(&z, Z_NO_FLUSH);
    have = out.size() - z.avail_out;
  }
  inflateEnd(&z);
  if (r != Z_STREAM_END) return {};
  out.resize(have);
  return out;
}

