#!/usr/bin/env bash
# Builds the on-device tools for Android arm64 into stage/:
#   clang, lld  (LLVM 22.1.8, configure_android_llvm.sh; about 50 min the first time),
#               and clang's resource headers (stage/lib/clang/22/include)
#   XenonRecomp (XR_SRC: the pinned, patched checkout, read only; one binary
#                serves both games: only the ppc_context.h template differs, and that is
#                passed on the command line from each game's profile)
#   libstfsextract.so (stfsextract/: SoD's STFS extraction, a JNI library)
# Paths: env.sh. Then package.sh lays them out for the launcher.
# Usage: build_tools.sh [llvm|xr|stfs|all]
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
. "$HERE/env.sh"
STFS_SRC=$HERE/stfsextract
STAGE=$HERE/stage/bin
what=${1:-all}
mkdir -p "$STAGE"

if [ "$what" = llvm ] || [ "$what" = all ]; then
  LLVM_BUILD=${LLVM_BUILD_DIR:-$HERE/build-android}
  [ -f "$LLVM_BUILD/build.ninja" ] || "$HERE/configure_android_llvm.sh"
  "$NINJA" -C "$LLVM_BUILD" clang lld
  "$STRIP" --strip-all -o "$STAGE/clang" "$LLVM_BUILD/bin/clang"
  "$STRIP" --strip-all -o "$STAGE/lld" "$LLVM_BUILD/bin/lld"
  # clang's resource headers, some generated by its build (arm_neon.h): for the kit.
  rm -rf "$HERE/stage/lib/clang/22"
  mkdir -p "$HERE/stage/lib/clang/22"
  cp -r "$LLVM_BUILD/lib/clang/22/include" "$HERE/stage/lib/clang/22/"
fi

if [ "$what" = xr ] || [ "$what" = all ]; then
  [ -f "$HERE/build-xenonrecomp/build.ninja" ] || "$CMAKE" -G Ninja -S "$XR_SRC" -B "$HERE/build-xenonrecomp" \
    -DCMAKE_MAKE_PROGRAM="$NINJA" \
    -DCMAKE_TOOLCHAIN_FILE="$NDK/build/cmake/android.toolchain.cmake" \
    -DANDROID_ABI=arm64-v8a -DANDROID_PLATFORM=android-29 -DANDROID_SUPPORT_FLEXIBLE_PAGE_SIZES=ON \
    -DCMAKE_EXE_LINKER_FLAGS="-Wl,-z,max-page-size=16384" \
    -DCMAKE_BUILD_TYPE=Release
  "$NINJA" -C "$HERE/build-xenonrecomp" XenonRecomp
  "$STRIP" --strip-all -o "$STAGE/XenonRecomp" "$HERE/build-xenonrecomp/XenonRecomp/XenonRecomp"
fi

if [ "$what" = stfs ] || [ "$what" = all ]; then
  # libstfsextract.so: SoD's STFS extraction, loaded by the launcher in-process (JNI).
  [ -f "$HERE/build-stfsextract/build.ninja" ] || "$CMAKE" -G Ninja -S "$STFS_SRC" -B "$HERE/build-stfsextract" \
    -DCMAKE_MAKE_PROGRAM="$NINJA" \
    -DCMAKE_TOOLCHAIN_FILE="$NDK/build/cmake/android.toolchain.cmake" \
    -DANDROID_ABI=arm64-v8a -DANDROID_PLATFORM=android-29 -DANDROID_SUPPORT_FLEXIBLE_PAGE_SIZES=ON -DCMAKE_BUILD_TYPE=Release
  "$NINJA" -C "$HERE/build-stfsextract" stfsextract
  "$STRIP" --strip-unneeded -o "$STAGE/libstfsextract.so" "$HERE/build-stfsextract/libstfsextract.so"
fi

ls -la "$STAGE"
