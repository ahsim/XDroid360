#!/usr/bin/env bash
# P2 item 1: lays out the on-device tools and the game-agnostic toolchain kit for the
# launcher (recipe format v2, RECIPE_FORMAT_DRAFT.md, "Shipped pieces"):
#   out/jniLibs/arm64-v8a/libclang.so, liblld.so, libxenonrecomp.so, libstfsextract.so (stage/bin)
#   out/kit/   and out/kit.zip  -> the launcher extracts it to ${KIT}
#   kit/licenses/: the license texts of everything in the jniLibs and the kit (INDEX.md)
# The launcher's Gradle copies these as they are. Paths: env.sh.
# Run build_tools.sh first. Usage: package.sh  (RELEASE=v1.0.0 for a release; default: dev)
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
. "$HERE/env.sh"
NDK_SYSROOT=$NDK_LLVM/sysroot
NDK_RT=$NDK_LLVM/lib/clang/18/lib/linux
LLVM_SRC=$HERE/src/llvm-project-$LLVM_VERSION.src
# clang's resource headers (some generated by its build), staged next to the binaries.
CLANG_HEADERS=$HERE/stage/lib/clang/22/include
RELEASE=${RELEASE:-dev}
# The launcher's own SDL (its libSDL3.so is what the games link against).
SDL3_HEADERS=$SDL_SRC/include/SDL3
STAGE=$HERE/stage/bin
OUT=$HERE/out
KIT=$OUT/kit
TRIPLE=aarch64-linux-android

for f in "$STAGE/clang" "$STAGE/lld" "$STAGE/XenonRecomp" "$STAGE/libstfsextract.so" "$CLANG_HEADERS/arm_neon.h"; do
  [ -f "$f" ] || { echo "missing $f: run build_tools.sh" >&2; exit 1; }
done

# Versions the recipes check (requires.tools) and the launcher stores per instance.
clang_ver=$(sed -n 's/^set(LLVM_VERSION_MAJOR \([0-9]*\)).*/\1/p; s/^  set(LLVM_VERSION_MAJOR \([0-9]*\)).*/\1/p' \
  "$LLVM_SRC/cmake/Modules/LLVMVersion.cmake" | head -1)
[ "$clang_ver" = 22 ] || { echo "unexpected LLVM version '$clang_ver'" >&2; exit 1; }
# XenonRecomp must be the pinned commit, patched (the marker only the pinned script writes).
[ "$(git -C "$XR_SRC" rev-parse HEAD)" = "$XR_COMMIT" ] ||
  { echo "$XR_SRC isn't XenonRecomp $XR_COMMIT" >&2; exit 1; }
grep -q '(XDroid360) A config path' "$XR_SRC/XenonRecomp/recompiler_config.cpp" ||
  { echo "$XR_SRC isn't patched with patch_recompiler.py $XR_PATCH_COMMIT" >&2; exit 1; }
sdl_ver=$(awk '/define SDL_MAJOR_VERSION/ {a=$3} /define SDL_MINOR_VERSION/ {b=$3} /define SDL_MICRO_VERSION/ {c=$3} END {print a"."b"."c}' "$SDL3_HEADERS/SDL_version.h")

# Only this script's outputs: out/games/ holds the game profiles (each game's make_profile.sh).
rm -rf "$OUT/jniLibs" "$KIT" "$OUT/kit.zip"
mkdir -p "$OUT/jniLibs/arm64-v8a"
cp "$STAGE/clang" "$OUT/jniLibs/arm64-v8a/libclang.so"
cp "$STAGE/lld" "$OUT/jniLibs/arm64-v8a/liblld.so"
cp "$STAGE/XenonRecomp" "$OUT/jniLibs/arm64-v8a/libxenonrecomp.so"
cp "$STAGE/libstfsextract.so" "$OUT/jniLibs/arm64-v8a/libstfsextract.so"

# The kit: what the phone's compile and link need from the NDK (the same NDK as the
# games' prebuilt runtimes), clang 22's own headers, and the SDL3 headers.
mkdir -p "$KIT/sysroot/usr/lib/$TRIPLE" "$KIT/clang/22" "$KIT/clang/lib" "$KIT/sdl3/include"
cp -r "$NDK_SYSROOT/usr/include" "$KIT/sysroot/usr/"
cp -r "$NDK_SYSROOT/usr/lib/$TRIPLE/29" "$KIT/sysroot/usr/lib/$TRIPLE/"
cp "$NDK_SYSROOT/usr/lib/$TRIPLE/libc++_static.a" "$NDK_SYSROOT/usr/lib/$TRIPLE/libc++abi.a" \
   "$KIT/sysroot/usr/lib/$TRIPLE/"
# The NDK driver finds these in its resource dir; the recipe's link line only has the
# sysroot's -L paths, so they go next to libc++ (-latomic, -l:libunwind.a).
cp "$NDK_RT/aarch64/libunwind.a" "$NDK_RT/aarch64/libatomic.a" "$KIT/sysroot/usr/lib/$TRIPLE/"
cp "$NDK_RT/libclang_rt.builtins-aarch64-android.a" "$KIT/clang/lib/"
cp -r "$CLANG_HEADERS" "$KIT/clang/22/"
cp -r "$SDL3_HEADERS" "$KIT/sdl3/include/"

cat > "$KIT/kit.json" <<EOF
{
  "kit": 1,
  "release": "$RELEASE",
  "ndk": "27.3.13750724",
  "clang": "22.1.8",
  "sdl3": "$sdl_ver",
  "tools": { "clang": "22.1.8", "lld": "22.1.8", "xenonrecomp": "$XR_VERSION" }
}
EOF

# The license texts, for the jniLibs (in the APK beside the kit) and the kit itself.
LIC=$KIT/licenses
mkdir -p "$LIC"
lic() {  # lic <name in licenses/> <source file>
  [ -f "$2" ] || { echo "missing license text $2" >&2; exit 1; }
  cp "$2" "$LIC/$1"
}
lic LLVM.txt "$LLVM_SRC/llvm/LICENSE.TXT"
lic NDK-NOTICE.txt "$NDK/NOTICE"
lic NDK-NOTICE-toolchain.txt "$NDK/NOTICE.toolchain"
lic SDL3.txt "$SDL_SRC/LICENSE.txt"
lic XenonRecomp.md "$XR_SRC/LICENSE.md"
lic GPL-2.0.txt "$HERE/licenses/GPL-2.0.txt"
lic LGPL-2.1.txt "$XR_SRC/thirdparty/libmspack/libmspack/COPYING.LIB"
lic fmt.txt "$XR_SRC/thirdparty/fmt/LICENSE"
lic tomlplusplus.txt "$XR_SRC/thirdparty/tomlplusplus/LICENSE"
lic xxHash.txt "$XR_SRC/thirdparty/xxHash/LICENSE"
lic SIMDe.txt "$XR_SRC/thirdparty/simde/COPYING"
lic tiny-AES-c.txt "$XR_SRC/thirdparty/tiny-AES-c/unlicense.txt"
sed -n '1,/\*\//p' "$XR_SRC/thirdparty/TinySHA1/TinySHA1.hpp" > "$LIC/TinySHA1.txt"
lic stfsextract.txt "$HERE/stfsextract/LICENSE"
cat > "$LIC/INDEX.md" <<EOF
# Licenses: the on-device tools and the toolchain kit

| Component | Where | License | Text | Source |
|---|---|---|---|---|
| clang, lld 22.1.8 | libclang.so, liblld.so; clang/22/include | Apache-2.0 WITH LLVM-exception | LLVM.txt | https://github.com/llvm/llvm-project/releases/tag/llvmorg-22.1.8 |
| NDK r27d (27.3.13750724): Bionic headers and stubs, crt objects | sysroot/ | see NOTICE | NDK-NOTICE.txt | https://developer.android.com/ndk/downloads |
| NDK r27d: libc++, libc++abi, libunwind, libatomic, compiler-rt builtins | sysroot/usr/lib, clang/lib | Apache-2.0 WITH LLVM-exception (see NOTICE) | NDK-NOTICE-toolchain.txt | https://developer.android.com/ndk/downloads |
| SDL $sdl_ver headers | sdl3/include | Zlib | SDL3.txt | https://github.com/libsdl-org/SDL |
| XenonRecomp $XR_VERSION | libxenonrecomp.so | MIT; **the binary as a whole is GPL-2.0-or-later** (its PowerPC disassembler, thirdparty/disasm, is from GNU binutils) | XenonRecomp.md, GPL-2.0.txt | https://github.com/hedge-dev/XenonRecomp at $XR_COMMIT, patched by scripts/patch_recompiler.py of https://github.com/$XR_PATCH_REPO at $XR_PATCH_COMMIT; the release's xenonrecomp-source tarball holds both |
| in XenonRecomp: libmspack (lzxd.c) | libxenonrecomp.so | LGPL-2.1 | LGPL-2.1.txt | https://github.com/kyz/libmspack |
| in XenonRecomp: fmt, toml++, xxHash, SIMDe, tiny-AES-c, TinySHA1 | libxenonrecomp.so | MIT, MIT, BSD-2-Clause, MIT, Unlicense, ISC-style | fmt.txt, tomlplusplus.txt, xxHash.txt, SIMDe.txt, tiny-AES-c.txt, TinySHA1.txt | XenonRecomp's thirdparty/ |
| libstfsextract (SoD's STFS reader, a port of SoDRecomp's) | libstfsextract.so | MIT | stfsextract.txt | https://github.com/udarmolota/XDroid360 (toolchain/stfsextract/) |
EOF

# kit.zip, for the launcher's assets. Python's zipfile: Git Bash has no zip. (The first Python
# that runs: Windows has a python3 that only opens the Store; Linux may have no python.)
for PYTHON in python3 python; do "$PYTHON" -c "" 2>/dev/null && break; done
(cd "$OUT" && "$PYTHON" -I -c '
import os, sys, zipfile
with zipfile.ZipFile("kit.zip", "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    for root, dirs, files in os.walk("kit"):
        dirs.sort()
        for f in sorted(files):
            p = os.path.join(root, f)
            z.write(p, os.path.relpath(p, "kit").replace(os.sep, "/"))
')

cat "$KIT/kit.json"
du -sh "$OUT/jniLibs/arm64-v8a"/* "$KIT" "$OUT/kit.zip"
